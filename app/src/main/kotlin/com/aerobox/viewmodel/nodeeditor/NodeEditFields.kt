enum class EditorSection(val title: Int) {
    GENERAL(R.string.node_edit_section_general), AUTH(R.string.node_edit_section_authentication),
    TRANSPORT(R.string.node_edit_section_transport), PROTOCOL(R.string.node_edit_section_protocol_options),
    TLS(R.string.node_edit_section_tls), REALITY(R.string.node_edit_section_reality),
    TLS_ADVANCED(R.string.node_edit_section_tls_advanced), ECH(R.string.node_edit_section_ech),
    MUX(R.string.node_edit_section_mux), DIAL(R.string.node_edit_section_dial)
}
enum class EditorInput { TEXT, SECRET, MULTILINE, NUMBER, BOOLEAN, OPTIONAL_BOOLEAN }

data class NodeEditField(
    val key: String,
    val label: Int,
    val section: EditorSection,
    val input: EditorInput,
    val advanced: Boolean = false,
    val choices: (ProxyNode) -> List<String> = { emptyList() },
    val visible: (ProxyNode) -> Boolean = { true },
    val read: (ProxyNode) -> String,
    val write: (ProxyNode, String) -> ProxyNode
)

