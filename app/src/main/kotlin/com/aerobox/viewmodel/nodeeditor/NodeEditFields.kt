    private fun canMultiplex(n: ProxyNode) = n.type in muxTypes &&
        (n.type !in ssTypes || (n.udpOverTcpEnabled == null && n.udpOverTcpVersion == null))
    fun hasTls(n: ProxyNode) = n.type !in ssTypes && n.type != ProxyType.SOCKS &&
        (n.type !in setOf(ProxyType.VMESS, ProxyType.VLESS, ProxyType.HTTP) || n.tls ||
            (n.type == ProxyType.VLESS && !n.publicKey.isNullOrBlank()))

